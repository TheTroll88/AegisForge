"""Generate proposed .env entries for Base token/router addresses using CoinGecko.

Writes a preview to stdout and to `proposed_base_env.txt` in the same folder.
"""
import requests
import time
import json
import os

COMMON_SYMBOLS = [
    "USDC", "USDT", "DAI", "WETH", "WBTC", "LINK", "UNI", "AAVE", "SUSHI", "FRAX"
]

CG_LIST_URL = "https://api.coingecko.com/api/v3/coins/list"

def build_symbol_map():
    r = requests.get(CG_LIST_URL, timeout=15)
    r.raise_for_status()
    coins = r.json()
    sym = {}
    for c in coins:
        s = c.get('symbol')
        if s:
            k = s.upper()
            if k not in sym:
                sym[k] = c['id']
    return sym

def fetch_platform_address(cg_id):
    url = f"https://api.coingecko.com/api/v3/coins/{cg_id}?localization=false"
    r = requests.get(url, timeout=15)
    r.raise_for_status()
    data = r.json()
    platforms = data.get('platforms') or {}
    # Try common keys
    for key in ('base', 'base-mainnet', 'basechain', 'base-chain'):
        addr = platforms.get(key)
        if addr:
            return addr
    # fallback: search any platform key containing 'base'
    for k,v in platforms.items():
        if 'base' in k.lower() and v:
            return v
    return None

def main():
    print("🔎 Building symbol map from CoinGecko...")
    symmap = build_symbol_map()
    results = {}
    for s in COMMON_SYMBOLS:
        cid = symmap.get(s)
        if not cid:
            results[s] = None
            continue
        try:
            addr = fetch_platform_address(cid)
            results[s] = addr
            if addr:
                print(f"{s}: {addr}")
            else:
                print(f"{s}: not found on Base via CoinGecko")
        except Exception as e:
            results[s] = None
            print(f"{s}: error fetching ({e})")
        time.sleep(0.2)

    # Propose env content
    env_lines = []
    env_lines.append("# Proposed Base token/router addresses generated by script")
    # Router: we won't guess router; leave for user to confirm commonly used router
    env_lines.append("# Set UNISWAP_ROUTER to the desired DEX router on Base")
    for s,a in results.items():
        key = f"TOKEN_{s}"
        val = a or ""
        env_lines.append(f"{key}={val}")

    out_path = os.path.join(os.path.dirname(__file__), 'proposed_base_env.txt')
    with open(out_path, 'w') as f:
        f.write('\n'.join(env_lines))

    print('\n✅ Proposal written to:', out_path)
    print('\nPreview:')
    print('\n'.join(env_lines))

if __name__ == '__main__':
    main()
